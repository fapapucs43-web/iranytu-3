/**
 * Icon set registry (Batch 7, P12).
 *
 * PURE DATA — no React, no DOM, no `document`, no network. Everything the
 * picker and the tests need lives here so it can be exercised in Bun without
 * a browser. Drawing happens in `state/IconSetContext.tsx`; nothing in this
 * module can reach the network, which is the point of the split.
 *
 * WHY THIS IS AN ALLOWLIST AND NOT A LOADER
 * The app renders exactly 29 distinct emoji as icons (see GLYPHS below). A
 * general "emoji font" or "3D pack" would mean thousands of assets to cover
 * glyphs this app never draws. So each set ships only the 29, and the mapping
 * is explicit and reviewable: a set that cannot supply one of them simply does
 * not offer it, rather than silently rendering the wrong picture.
 *
 * WHY THE STORED DATA NEVER CHANGES
 * `DEFAULT_ACTIVITIES` keeps the emoji inside the label string ("🚶 Mozgás"),
 * because `correlationGrid` matches entries on that exact string. Changing the
 * format would silently zero every existing user's correlation history. So a
 * set changes only HOW a glyph is drawn, never WHAT is stored: the data stays
 * `"🚶 Mozgás"` and `useIcon` resolves the leading glyph at render time.
 */

/** A set the user can choose. Ordered as they appear in the picker. */
export type IconSetId = "lucide" | "system" | "fluent";

