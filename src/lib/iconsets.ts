// The artwork itself. GENERATED by `bun scripts/vendor-fluent-artwork.ts`.
//
// It used to be imported here statically, which put half a megabyte of SVG in
// the entry chunk for readers who never pick a 3D set — and `lucide` is the
// default. It is now reached through the loader below: a `dynamic import`, so
// it becomes its own chunk that only arrives if and when an inline set is
// actually chosen. The precache list that chunk is written into, so reaching it
// offline works exactly as reaching a cached asset always did.
//
// WHY A LOADER AND NOT AN `async` LOOKUP. Every caller of this module draws
// inside a React render and already has a fallback branch for "no artwork",
// which is the branch that used to be unreachable. Returning `undefined` until
// the module lands reuses that branch unchanged: the icon draws as Lucide on
// the first paint and upgrades in place. Making the lookup itself async would
// have rewritten four components to await something they can already render
// without.
type FluentArtworkModule = typeof import("./iconsets/fluent-artwork");

let artworkModule: FluentArtworkModule | null = null;
let pending: Promise<void> | null = null;

/**
 * Fetch the artwork module, at most once.
 *
 * The promise is kept rather than discarded so two components mounting in the
 * same tick share one request, and a rejection is not retried on every render
 * — a failed load shows Lucide, which is a good answer, and hammering a chunk
 * that will not arrive is not.
 */
export function loadFluentArtwork(): Promise<void> {
  if (artworkModule) return Promise.resolve();
  if (!pending) {
    pending = import("./iconsets/fluent-artwork").then((module) => {
      artworkModule = module;
    });
  }
  return pending;
}

/**
 * The artwork for a stem, or `undefined` if it has not been loaded yet.
 *
 * Synchronous on purpose — see the loader's note above. Callers treat
 * `undefined` exactly as they treat a stem the artwork does not carry.
 */
export function fluentArtworkSync(stem: string | undefined): string | undefined {
  return artworkModule?.fluentArtwork(stem);
}

/**
 * How a set draws.
 *
 *   component → React components from lib/icons. Nothing to load.
 *   text      → the literal character, drawn by the OS. Nothing to load.
 *   inline    → an SVG string compiled INTO the bundle. Nothing to load, and
 *               nothing that can be missing at runtime.
 *
 * There is no fourth kind. Batch 7 had `file` — "fetch these from our own
 * origin when the user picks the set" — and Batch 7b removed it, because every
 * remaining set is either free or inlined. A kind that no set uses is a code
 * path that cannot be tested, and the module that drove it (and its 154 lines
 * of warm-up, retry and per-glyph failure bookkeeping) went with it.
 */
export type IconSetKind = "component" | "text" | "inline";

export type LicenceId = "ISC" | "n/a" | "MIT" | "CC-BY-4.0";

export type Resource = {
  label: string;
  phone?: string;
  hours?: string;
  href?: string;
};

/**
 * One user-selectable set.
 *
 * There is no `base` path field. Batch 7 had one, for the sets whose artwork
 * was fetched from `/iconsets/<set>-v<n>/`; with the artwork inlined no set
 * has a directory, and a field no set fills is a field nothing reads.
 */
export type IconSetDef = {
  id: IconSetId;
  /** Shown in the picker. */
  label: string;
  /** One line, plain Hungarian, describing what the user gets. */
  blurb: string;
  kind: IconSetKind;
  /** Download cost shown in the picker. Zero for all three: nothing is fetched. */
  downloadBytes: number;
  /** Human label for the cost, e.g. "kb. 40 kB". */
  downloadLabel: string;
  /** Whether picking this set costs the user a download. */
  downloads: boolean;
  licence: LicenceId;
  /** Who made it, for the Settings → Licences list. */
  credit: string;
  /** Where the artwork came from. */
  source: string;
  /** One-line licence terms, shown to the user in plain words. */
  licenceNote: string;
};

/** What `useIcon` draws for one glyph under one selection. */
export type RenderMode = "emoji" | "component" | "inline";

/**
 * THE 29 GLYPHS.
 *
 * Every emoji the app renders as an icon, with the Lucide component that
 * draws it today. This list is the contract between the data files and the
 * sets: `mood.ts`, `store.ts`, `achievements.ts`, `trackers.ts` and
 * `habits.ts` all draw from it.
 */
export type GlyphDef = {
  /** The emoji as it appears in stored data. */
  glyph: string;
  /**
   * The emoji's Unicode codepoints, lowercase hex, no separators.
   *
   * Not a filename any more. Batch 7 used this as the Twemoji stem; with the
   * set withdrawn it is simply the glyph's identity, kept because it is how
   * two look-alike characters (🏔️ and ⛰) are told apart in review, and
   * because a test pins its shape. No runtime path reads it.
   */
  codepoints: string;
  /** The Lucide component name used for the default set and every fallback. */
  lucide: string;
  /**
   * The Fluent `modern` filename stem. Figures use the genderless `person-`
   * form and the `default` (medium) skin tone: 27 of the 29 have no human
   * figure at all, and the two that do (🧘 Relaxáció, 🚶 Mozgás) both exist as
   * `person-in-lotus-position-default` and `person-walking-default`. A test
   * fails if any entry starts with man-/woman-/male-/female-.
   */
  fluent?: string;
};

