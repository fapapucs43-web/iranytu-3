/** The default. Batch 7 must change nothing for a user who never opens Settings. */
export const DEFAULT_ICON_SET: IconSetId = "lucide";

const BY_ID: Record<string, IconSetDef> = Object.fromEntries(
  ICON_SETS.map((s) => [s.id, s]),
);

/** Narrow an unknown value (localStorage, a future import) to a real set id. */
export function isIconSetId(v: unknown): v is IconSetId {
  return typeof v === "string" && Object.prototype.hasOwnProperty.call(BY_ID, v);
}

/**
 * Read a set id defensively. A corrupt or unknown value falls back to Lucide
 * rather than throwing — the app must always be able to draw its own icons.
 */
export function coerceIconSetId(v: unknown): IconSetId {
  return isIconSetId(v) ? v : DEFAULT_ICON_SET;
}

export function iconSetDef(id: unknown): IconSetDef {
  return BY_ID[coerceIconSetId(id)];
}

/** Every valid id, in picker order. */
export const ICON_SET_IDS: readonly IconSetId[] = ICON_SETS.map((s) => s.id);

/**
 * The definition for one emoji, or undefined when the app does not draw it.
 *
 * Returns undefined for a glyph that is genuinely not in the set (a
 * user-typed custom emoji, say). The caller renders the literal character in
 * that case — which is the correct behaviour, not a fallback.
 */
export function glyphDef(glyph: string): GlyphDef | undefined {
  return GLYPHS.find((g) => g.glyph === glyph);
}

/**
 * The emoji that stands for a Lucide icon name, or undefined.
 *
 * THE REVERSE OF `glyphDef`, and the reason Batch 7f needed it.
 * Most of the app draws an icon by its Lucide name — a section header wants
 * "the flame", a card title wants "the trophy" — and only some of those names
 * are also the ones the data stores as an emoji. This maps the first to the
 * second so a call site can keep saying `<ContentIcon name="Flame" />` and
 * still land on the set's own artwork.
 *
 * Returns undefined when no emoji backs that name, and that is not an error:
 * it is how `lib/icon-policy.ts` decides an icon is chrome and belongs in a
 * button rather than in the picture set. The two functions are deliberately
 * exact inverses over `GLYPHS` — a name maps to an emoji only if that emoji
 * maps back to the same name — so there is one answer whichever way you ask.
 */
export function glyphForLucideName(lucide: string): string | undefined {
  return GLYPHS.find((g) => g.lucide === lucide)?.glyph;
}

/**
 * How one glyph should be drawn for a given selection.
 *
 * `selected === undefined` means the user has never chosen, and renders
 * exactly what the app rendered before Batch 7: the literal character.
 * `system` also renders the literal character, but because the user chose it.
 * The distinction is invisible in the output and only matters to the picker,
 * which shows "no set chosen" as the pre-Batch-7 state.
 */
export function renderModeFor(selected: unknown, glyph: string): RenderMode {
  if (!glyphDef(glyph)) return "emoji"; // not ours: draw the character
  if (selected === undefined || selected === "system") return "emoji";
  const set = iconSetDef(selected);
  return set.kind === "inline" ? "inline" : "component";
}

/** True when this selection changes nothing about how the app looks. */
export function isPristineSelection(selected: unknown): boolean {
  return selected === undefined || selected === "system";
}

/**
 * The inline SVG fragment for one glyph in an artwork set, or undefined.
 *
 * The key is the set's own stem, not the emoji: Fluent is named by its English
 * slug (`person-walking-default`), and the nav's ⚙️ has no emoji in `GLYPHS` at
 * all. Callers that already hold a stem — the nav — use `fluentArtwork`
 * directly; this exists for callers holding an emoji out of the data.
 *
 * Replaces `glyphHref`, which built a URL to fetch. Nothing is fetched now, so
 * there is no URL to build and nothing that can 404 at runtime.
 *
 * Returns `undefined` until `loadFluentArtwork()` has run — which is not a new
 * failure mode but the one this function always had, since the artwork module
 * and the registry are generated from the same source.
 */
export function glyphArtwork(setId: unknown, glyph: string): string | undefined {
  if (iconSetDef(setId).kind !== "inline") return undefined;
  const g = glyphDef(glyph);
  if (!g?.fluent) return undefined;
  return fluentArtworkSync(g.fluent);
}

/**
 * Every piece a set needs, as (glyph, stem) pairs.
 *
 * Replaces the href list Batch 7 precached. There is nothing to precache now:
 * the artwork is in the bundle, so there is no request to make before the icons
 * can draw, no cache that can go stale, and nothing that can be missed.
 */
export function setAssets(setId: unknown): { glyph: string; stem: string }[] {
  if (iconSetDef(setId).kind !== "inline") return [];
  const seen = new Set<string>();
  const out: { glyph: string; stem: string }[] = [];
  for (const g of GLYPHS) {
    if (seen.has(g.glyph)) continue; // GLYPHS repeats 🌿 and 📚
    seen.add(g.glyph);
    if (g.fluent) out.push({ glyph: g.glyph, stem: g.fluent });
  }
  return out;
}

/** Every stem a set draws. For tests and the licence screen. */
export function setStems(setId: unknown): string[] {
  return [...new Set(setAssets(setId).map((a) => a.stem))];
}

/** Total bytes a set costs, summed over its distinct assets. */
export function setDownloadBytes(setId: unknown): number {
  const set = iconSetDef(setId);
  if (!set.downloads) return 0;
  return set.downloadBytes;
}

/** For the Settings → Licences screen. */
export type LicenceEntry = {
  setId: IconSetId;
  label: string;
  source: string;
  licence: LicenceId;
  licenceNote: string;
  credit: string;
  used: boolean;
};

export function licenceEntries(selected: unknown): LicenceEntry[] {
  const active = coerceIconSetId(selected);
  return ICON_SETS.map((s) => ({
    setId: s.id,
    label: s.label,
    source: s.source,
    licence: s.licence,
    licenceNote: s.licenceNote,
    credit: s.credit,
    used: s.id === active,
  }));
}
